// TypeORM gives UPDATE ... RETURNING back as [rows, count] but INSERT as plain rows, so this evens them out.
export function returned<T>(result: unknown): T[] {
  if (
    Array.isArray(result) &&
    result.length === 2 &&
    Array.isArray(result[0]) &&
    typeof result[1] === 'number'
  ) {
    return result[0] as T[];
  }
  return result as T[];
}
